CREATE OR REPLACE TABLE FEATURES.DELIVERY_FEATURES (
    ID                           VARCHAR,
    DELIVERY_PERSON_ID          VARCHAR,
    DELIVERY_PERSON_AGE        NUMBER,
    DELIVERY_PERSON_RATINGS    FLOAT,

    RESTAURANT_LATITUDE        FLOAT,
    RESTAURANT_LONGITUDE       FLOAT,
    DELIVERY_LOCATION_LATITUDE FLOAT,
    DELIVERY_LOCATION_LONGITUDE FLOAT,

    DISTANCE_KM                FLOAT,

    ORDER_DATE                 DATE,
    ORDER_HOUR                 NUMBER,
    PICKUP_DELAY_MIN           NUMBER,

    WEATHERCONDITIONS          VARCHAR,
    ROAD_TRAFFIC_DENSITY       VARCHAR,
    VEHICLE_CONDITION          NUMBER,
    TYPE_OF_ORDER              VARCHAR,
    TYPE_OF_VEHICLE            VARCHAR,
    MULTIPLE_DELIVERIES        NUMBER,
    FESTIVAL                   VARCHAR,
    CITY                       VARCHAR,

    TIME_TAKEN                 NUMBER
);


INSERT INTO FEATURES.DELIVERY_FEATURES
SELECT
    ID,
    DELIVERY_PERSON_ID,
    DELIVERY_PERSON_AGE,
    DELIVERY_PERSON_RATINGS,

    RESTAURANT_LATITUDE,
    RESTAURANT_LONGITUDE,
    DELIVERY_LOCATION_LATITUDE,
    DELIVERY_LOCATION_LONGITUDE,

    -- Distance between restaurant and delivery location
    2 * 6371 * ASIN(
        SQRT(
            POWER(
                SIN(
                    RADIANS(
                        DELIVERY_LOCATION_LATITUDE - RESTAURANT_LATITUDE
                    ) / 2
                ),
                2
            )
            +
            COS(RADIANS(RESTAURANT_LATITUDE))
            * COS(RADIANS(DELIVERY_LOCATION_LATITUDE))
            * POWER(
                SIN(
                    RADIANS(
                        DELIVERY_LOCATION_LONGITUDE - RESTAURANT_LONGITUDE
                    ) / 2
                ),
                2
            )
        )
    ) AS DISTANCE_KM,

    ORDER_DATE,

    -- Hour of order
    EXTRACT(HOUR FROM TIME_ORDERD) AS ORDER_HOUR,

    -- Time between order and pickup
    DATEDIFF(
        'minute',
        TIME_ORDERD,
        TIME_ORDER_PICKED
    ) AS PICKUP_DELAY_MIN,

    WEATHERCONDITIONS,
    ROAD_TRAFFIC_DENSITY,
    VEHICLE_CONDITION,
    TYPE_OF_ORDER,
    TYPE_OF_VEHICLE,
    MULTIPLE_DELIVERIES,
    FESTIVAL,
    CITY,

    -- Target variable
    TIME_TAKEN

FROM CLEAN.DELIVERY_CLEAN;

SELECT
    ID,
    DISTANCE_KM,
    ORDER_HOUR,
    PICKUP_DELAY_MIN,
    ROAD_TRAFFIC_DENSITY,
    WEATHERCONDITIONS,
    TYPE_OF_VEHICLE,
    MULTIPLE_DELIVERIES,
    TIME_TAKEN
FROM FEATURES.DELIVERY_FEATURES
LIMIT 10;

