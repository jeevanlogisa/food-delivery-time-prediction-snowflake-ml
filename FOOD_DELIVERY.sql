UPDATE CLEAN.DELIVERY_CLEAN AS C
SET TIME_TAKEN = TRY_TO_NUMBER(
    REGEXP_SUBSTR(R.TIME_TAKEN, '\\d+')
)
FROM RAW.DELIVERY_RAW AS R
WHERE C.ID = R.ID;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(TIME_TAKEN) AS NON_NULL_TARGET,
    COUNT_IF(TIME_TAKEN IS NULL) AS NULL_TARGET,
    MIN(TIME_TAKEN) AS MIN_TIME,
    MAX(TIME_TAKEN) AS MAX_TIME
FROM CLEAN.DELIVERY_CLEAN;


UPDATE FEATURES.DELIVERY_FEATURES AS F
SET TIME_TAKEN = C.TIME_TAKEN
FROM CLEAN.DELIVERY_CLEAN AS C
WHERE F.ID = C.ID;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(TIME_TAKEN) AS NON_NULL_TARGET,
    COUNT_IF(TIME_TAKEN IS NULL) AS NULL_TARGET,
    MIN(TIME_TAKEN) AS MIN_TIME,
    MAX(TIME_TAKEN) AS MAX_TIME
FROM FEATURES.DELIVERY_FEATURES;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(TIME_TAKEN) AS TARGET_AVAILABLE,
    COUNT_IF(TIME_TAKEN IS NULL) AS TARGET_NULL,
    MIN(TIME_TAKEN) AS MIN_DELIVERY_TIME,
    MAX(TIME_TAKEN) AS MAX_DELIVERY_TIME
FROM FEATURES.DELIVERY_FEATURES;

